export const BREEDS: BreedInfo[] = [...DOG_ROWS.map(make('dog')), ...CAT_ROWS.map(make('cat'))];

export const breedBySlug = (slug: string) => BREEDS.find((b) => b.slug === slug);

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

/** Finds a guide entry for a free-text breed name (name, slug or alias). */
export function findBreed(name: string | undefined, species?: 'dog' | 'cat' | 'other'): BreedInfo | undefined {
  if (!name) return undefined;
  const n = norm(name);
  if (!n) return undefined;
  const pool = species === 'dog' || species === 'cat' ? BREEDS.filter((b) => b.species === species) : BREEDS;
  return pool.find((b) => norm(b.name) === n || norm(b.slug) === n || (b.aliases ?? []).some((a) => norm(a) === n));
}

export const breedNames = (species?: 'dog' | 'cat') => BREEDS.filter((b) => !species || b.species === species).map((b) => b.name);
